# Sourced from ~/.bashrc in WSL (installed by install_ros_wsl.sh). Do not run directly.
#
# Why: in WSL "mirrored" networking, Linux also sees Tailscale (100.x) and WSL's internal DNS
# address (10.255.255.254). Fast DDS (ROS 2's default middleware) advertises itself on all of
# them and then fails to connect, so ROS nodes don't find each other, not even inside WSL.
# Fix: let Fast DDS use only the home-network address and localhost, over plain UDP.
# The address is looked up every time a shell starts, so a new IP from the router is fine.

__rover_lan_ip="$(ip -4 route get 1.1.1.1 2>/dev/null | sed -n 's/.* src \([0-9.]*\).*/\1/p')"
if [ -n "$__rover_lan_ip" ]; then
  mkdir -p "$HOME/.ros"
  cat > "$HOME/.ros/fastdds_wsl.xml" <<EOF
<?xml version="1.0" encoding="UTF-8" ?>
<!-- Generated by wsl_ros_network.sh: Fast DDS only on $__rover_lan_ip and localhost -->
<profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <transport_descriptors>
    <transport_descriptor>
      <transport_id>lan_udp</transport_id>
      <type>UDPv4</type>
      <interfaceWhiteList>
        <address>$__rover_lan_ip</address>
        <address>127.0.0.1</address>
      </interfaceWhiteList>
    </transport_descriptor>
  </transport_descriptors>
  <participant profile_name="lan_only" is_default_profile="true">
    <rtps>
      <userTransports>
        <transport_id>lan_udp</transport_id>
      </userTransports>
      <useBuiltinTransports>false</useBuiltinTransports>
    </rtps>
  </participant>
</profiles>
EOF
  export FASTRTPS_DEFAULT_PROFILES_FILE="$HOME/.ros/fastdds_wsl.xml"
  export FASTDDS_DEFAULT_PROFILES_FILE="$HOME/.ros/fastdds_wsl.xml"
fi
unset __rover_lan_ip
